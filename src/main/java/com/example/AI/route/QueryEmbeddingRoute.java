package com.example.AI.route;

import com.example.AI.processor.GlobalExceptionProcessor;
import org.apache.camel.builder.RouteBuilder;
import org.apache.camel.model.rest.RestBindingMode;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

import java.util.Map;

@Component
public class QueryEmbeddingRoute extends RouteBuilder {

    @Autowired
    private GlobalExceptionProcessor globalExceptionProcessor;

    public QueryEmbeddingRoute(GlobalExceptionProcessor globalExceptionProcessor) {
        this.globalExceptionProcessor = globalExceptionProcessor;
    }


    @Override
    public void configure() {

        /*
         * =========================================================
         * REST API
         * =========================================================
         */
        restConfiguration().component("servlet").bindingMode(RestBindingMode.json);

        onException(Exception.class)
                .log("error occurred while processing exception: ${exception.message}")
                .handled(true)
                .process(globalExceptionProcessor);

        rest()
                .post("/incidents/search")
                .consumes("application/json")
                .produces("application/json")
                .to("direct:search-incidents");


        from("direct:search-incidents")
                .routeId("search-incidents-api")
                .log("Received search request: ${body}")

                .process(exchange -> {

                    Map<String, Object> request = exchange.getMessage().getBody(Map.class);
                    String question = (String) request.get("question");

                    if (question == null || question.isBlank()) {
                        throw new IllegalArgumentException("question is required");
                    }

                    exchange.setProperty("userQuestion", question);
                    exchange.getMessage().setBody(question);
                })

                .to("langchain4j-embeddings:query-embedding")
                .log("Query embedding generated by Camel LangChain4j")
                .log("LangChain4j Body embedding>> ${body}")
                .log("LangChain4j header embedding >> ${in.headers}")
                /*
                 * -------------------------------------------------
                 * MILVUS SEARCH
                 * -------------------------------------------------
                 */

                .to("direct:search-similar-incidents")
                .log("Similar incidents found: ${body}")
                .to("direct:generate-rag-answer");
    }
}